/* 图片 CDN：国内直连 pages.dev 实测仅 24~41KB/s（图片慢的根因），jsDelivr testingcf 节点实测 ~140-380KB/s。
   jsDelivr 直读 GitHub 公开仓库的 public/images（主域名 cdn.jsdelivr.net 在国内被干扰，故用 testingcf 子域）。
   <img> 一律 src={resolveImg(path)} + data-src={path} + onError={onImgError}：CDN 失败自动回退站内同路径 */
export const IMG_CDN_BASE = 'https://testingcf.jsdelivr.net/gh/zhoucc155/homepage@main/public';
/* 站内媒体（/images/ 及根目录的封面、视频）统一走 CDN；外部绝对地址原样返回 */
const CDN_ASSET_RE = /\.(jpe?g|png|webp|gif|svg|mp4|webm)$/i;
export const resolveImg = (path: string) =>
  path.startsWith('/') && (path.startsWith('/images/') || CDN_ASSET_RE.test(path)) ? IMG_CDN_BASE + path : path;
/* 视频同样走 CDN：jsDelivr 支持 Range 请求（实测 206），可正常拖动进度与流式播放 */
export const resolveVideo = resolveImg;
/* 视频加载失败时回退站内同路径（与图片一致的一次性回退） */
export const onVideoError = (e: SyntheticEvent<HTMLVideoElement>) => {
  const el = e.currentTarget;
  if (el.dataset.fell) return;
  const fallback = el.getAttribute('data-src');
  if (fallback) {
    el.dataset.fell = '1';
    el.src = fallback;
  }
};
export const onImgError = (e: SyntheticEvent<HTMLImageElement>) => {
  const el = e.currentTarget;
  if (el.dataset.fell) return;
  const fallback = el.getAttribute('data-src');
  if (fallback) {
    el.dataset.fell = '1';
    el.src = fallback;
  }
};

